/* SSD teaching state. The photograph and final detections are saved Pi data;
 * offsets, logits and intermediate candidates are explicitly illustrative. */
(() => {
  "use strict";
  const M = window.DetectionMath;
  const data = window.DETECTION_LESSON_DATA;
  const $ = id => document.getElementById(id);
  const mint = "#65d8bb", amber = "#efc477", muted = "#a1b1c5";
  const offsets = [0.4, -0.6, 1.5, 2.0];
  const logits = M.LABELS.map(label => label === "chair" ? 4.2 : label === "background" ? 1.2 : label === "diningtable" ? 0.2 : -1.4);
  const scores = M.softmax(logits);
  const titles = ["Features retain position and learned patterns.", "Place reference shapes at every location.",
    "One box gets a class prediction and four offsets.", "Offsets adjust the reference box.",
    "Keep strong predictions; suppress duplicates.", "EdgeXR receives boxes in source pixels."];
  let stage = 0, headIndex = 0, priorIndex = 0;

  /** Format a number for the teaching panel. @param {number} value Number. @param {number} digits Precision. @returns {string} */
  function fixed(value, digits = 2) { return value.toFixed(digits); }

  /** Choose a cell near the saved chair; this is a teaching selection, not inference. @returns {object} */
  function current() {
    const head = M.HEADS[headIndex];
    const column = Math.min(head.grid - 1, Math.floor(0.14 * head.grid));
    const row = Math.min(head.grid - 1, Math.floor(0.60 * head.grid));
    const priors = M.priors(headIndex, column, row);
    const prior = priors[Math.min(priorIndex, priors.length - 1)];
    return { head, column, row, priors, prior, decoded: M.decode(prior, offsets) };
  }

  /** Draw a label on the model-space graphic using fixed lesson strings. @param {number} x X. @param {number} y Y. @param {string} label Text. @param {string} color Color. @returns {string} */
  function label(x, y, label, color = mint) {
    return `<text x="${x}" y="${y}" fill="${color}" stroke="#0a1119" stroke-width="2.4" paint-order="stroke" font-size="10" font-family="system-ui">${label}</text>`;
  }

  /** Draw normalized corner coordinates in 300-pixel teaching space. @param {number[]} box xyxy. @param {string} color Stroke. @param {boolean} dashed Reference style. @param {number} opacity Opacity. @returns {string} */
  function boxShape(box, color, dashed = false, opacity = 1) {
    return `<rect x="${box[0] * 300}" y="${box[1] * 300}" width="${(box[2] - box[0]) * 300}" height="${(box[3] - box[1]) * 300}" fill="none" stroke="${color}" stroke-width="1.8" opacity="${opacity}" ${dashed ? 'stroke-dasharray="5 3"' : ""}/>`;
  }

  /** Construct fixed filtering cases around the currently decoded teaching candidate. @param {object} decoded Center/size box. @returns {object[]} */
  function candidates(decoded) {
    const a = M.corners(decoded);
    // A and B deliberately overlap; C and D are separate low-score examples.
    const b = a.map((value, index) => value + (index % 2 ? 0.01 : 0.015));
    return [
      { id: "A", label: "chair", score: scores[9], box: a },
      { id: "B", label: "chair", score: 0.72, box: b },
      { id: "C", label: "chair", score: 0.40, box: [0.68, 0.07, 0.86, 0.22] },
      { id: "D", label: "chair", score: 0.20, box: [0.72, 0.40, 0.90, 0.59] },
    ];
  }

  /** Paint the current mathematical operation over the actual saved photograph. @param {object} state Selected prior and decoded geometry. @returns {void} */
  function draw(state) {
    const svg = $("ssd-picture");
    const actual = stage === 5;
    svg.setAttribute("viewBox", actual ? "0 0 1280 720" : "0 0 300 300");
    svg.setAttribute("aria-label", titles[stage] + (actual ? " Actual saved Pi detections." : " Illustrative model-space overlay."));
    svg.classList.toggle("source-frame", actual);
    let graphic = `<image href="${data.image}" width="${actual ? 1280 : 300}" height="${actual ? 720 : 300}" preserveAspectRatio="none"/>`;
    if (actual) {
      // These are the original report's boxes, not results generated by toy offsets.
      graphic += data.detections.map(box => {
        const [x1, y1, x2, y2] = box.box_xyxy;
        return `<rect x="${x1}" y="${y1}" width="${x2-x1}" height="${y2-y1}" fill="none" stroke="${mint}" stroke-width="5"/>` +
          `<text x="${Math.max(8, x1)}" y="${Math.max(30, y1-10)}" fill="${mint}" stroke="#0a1119" stroke-width="5" paint-order="stroke" font-size="25" font-family="system-ui">${box.label} ${fixed(box.confidence)}</text>`;
      }).join("");
    } else {
      graphic += '<rect width="300" height="300" fill="#08121d" opacity=".22"/>';
      if (stage < 2) {
        const cell = 300 / state.head.grid;
        for (let i = 0; i <= state.head.grid; i++) {
          const p = i * cell;
          graphic += `<path d="M${p} 0V300M0 ${p}H300" stroke="#a6c9d7" stroke-width=".55" opacity=".5"/>`;
        }
        graphic += `<rect x="${state.column*cell}" y="${state.row*cell}" width="${cell}" height="${cell}" fill="${mint}" opacity=".38"/>`;
        if (stage === 1) state.priors.forEach((prior, i) => {
          graphic += boxShape(M.corners(prior), i === priorIndex ? amber : muted, true, i === priorIndex ? 1 : .45);
        });
        graphic += `<circle cx="${state.prior.cx*300}" cy="${state.prior.cy*300}" r="3" fill="${mint}"/>`;
        graphic += label(8, 18, `Cell [row ${state.row}, column ${state.column}]`);
      } else if (stage < 4) {
        graphic += boxShape(M.corners(state.prior), amber, true);
        graphic += label(8, 18, "Dashed: default reference", amber);
        if (stage === 3) {
          graphic += boxShape(M.corners(state.decoded), mint);
          graphic += `<path d="M${state.prior.cx*300} ${state.prior.cy*300}L${state.decoded.cx*300} ${state.decoded.cy*300}" stroke="${mint}" stroke-width="2"/>`;
          graphic += label(8, 33, "Solid: decoded candidate");
        }
      } else {
        const boxes = candidates(state.decoded), decisions = M.suppress(boxes);
        decisions.forEach(box => {
          const keep = box.reason === "keep";
          graphic += boxShape(box.box, keep ? mint : amber, !keep, keep ? 1 : .4);
          const x = Math.max(8, Math.min(278, box.box[0] * 300));
          const y = Math.max(15, Math.min(288, box.box[1] * 300 - (box.id === "B" ? -14 : 4)));
          graphic += label(x, y, box.id, keep ? mint : amber);
        });
      }
    }
    svg.innerHTML = graphic;
    $("ssd-image-label").textContent = actual ? "SOURCE FRAME / 1280×720" : "MODEL INPUT / 300×300";
    $("ssd-evidence").textContent = actual ? "Actual saved detections" : stage < 2 ? "Real Pi image · schematic overlay" : "Real Pi image · illustrative predictions";
    const notes = [
      "The grid shows spatial alignment. Actual feature maps are learned values; each cell can depend on an image region wider than the drawn cell.",
      "All reference shapes at this cell share a center. Choose a shape below. Boxes may extend beyond the input boundary.",
      "The example logits and offsets are teaching numbers. They are not extracted from this photograph by a running model.",
      "The same four example offsets are applied to your selected prior. Changing the prior changes the candidate; this does not guarantee a good fit.",
      "A–D are illustrative chair candidates. Solid green survives; faded dashed candidates are rejected by the rules beside the image.",
      "These two detections come from your saved Pi report. They are a separate measured example, not the output of our illustrative candidates.",
    ];
    $("ssd-image-note").textContent = notes[stage];
  }

  /** Build the compact six-scale explorer and the currently available reference shapes. @param {object} state Current selection. @returns {void} */
  function selectors(state) {
    $("ssd-scales").hidden = stage > 1;
    $("ssd-scales").innerHTML = M.HEADS.map((head, i) => `<button type="button" data-ssd-head="${i}" aria-pressed="${i===headIndex}">${head.grid}×${head.grid}<small>${head.channels} ch</small></button>`).join("");
    $("ssd-priors").hidden = stage !== 1;
    $("ssd-priors").innerHTML = state.priors.map((prior, i) => `<button type="button" data-ssd-prior="${i}" aria-pressed="${i===priorIndex}">${prior.label}</button>`).join("");
  }

  /** Show selected class probabilities while retaining all 21 scores in a disclosure. @returns {string} */
  function scoreBars() {
    return [9, 0, 11].map(i => `<div class="ssd-score ${i===0 ? "background" : ""}"><div><span>${M.LABELS[i]}</span><span>${fixed(scores[i], 3)}</span></div><i style="width:${scores[i]*100}%"></i></div>`).join("");
  }

  /** Explain one stage with exact graph sizes and explicit teaching-data provenance. @param {object} state Current selection. @returns {string} */
  function explanation(state) {
    const {head, priors, prior, decoded} = state;
    const k = priors.length, cells = head.grid * head.grid;
    if (stage === 0) return `<span class="ssd-tag">MODEL STRUCTURE</span>
      <p>The 300×300×3 input becomes stacks of learned features. SSD reads several stacks so it can predict boxes at different spatial scales.</p>
      <div class="ssd-equation">${head.name}: <strong>${head.grid}×${head.grid}×${head.channels}</strong><br>${cells} spatial locations · ${head.channels} values at each location</div>
      <p>${headIndex < 2 ? "MobileNet supplies this feature map." : "SSD’s extra convolution layers produce this smaller feature map from preceding features."} The channels describe learned patterns; they are no longer RGB color planes.</p>
      <p>Choose a grid below the image. Finer grids provide more candidate centers; coarser grids use larger reference shapes in this model. No grid is reserved exclusively for a particular object size.</p>
      <details><summary>Where the six maps come from</summary><table class="ssd-table"><thead><tr><th>Feature layer</th><th>Shape</th><th>Source</th></tr></thead><tbody>${M.HEADS.map((h,i)=>`<tr><td>${h.name}</td><td>${h.grid}×${h.grid}×${h.channels}</td><td>${i<2 ? "MobileNet" : "SSD extra layer"}</td></tr>`).join("")}</tbody></table></details>`;
    if (stage === 1) return `<span class="ssd-tag">FIXED GEOMETRY</span>
      <p>A <strong>default box</strong> (also called a prior or anchor) is a reference center, width and height. Its geometry comes from the model configuration, before any object is recognized.</p>
      <div class="ssd-number">${cells} × ${k} = ${cells*k}</div><p class="ssd-small">locations × shapes per location = priors on this map</p>
      <p>The highlighted cell has ${k} shapes. The selected <strong>${prior.label}</strong> spans ${fixed(prior.w*300,1)}×${fixed(prior.h*300,1)} model-input pixels. These shapes give the predictor starting geometries to adjust.</p>
      <div class="ssd-equation">All maps: 1,083 + 600 + 150 + 54 + 24 + 6<br><strong>1,917 default boxes per image</strong></div>
      <p>A default box is not an image crop and is not a claim that an object exists there. The network will score and adjust all of them.</p>`;
    if (stage === 2) return `<span class="ssd-tag toy">ILLUSTRATIVE PREDICTIONS</span>
      <p>Two prediction heads read the same feature map. For each prior, one predicts position/size adjustments; the other predicts a score for every class.</p>
      <div class="ssd-split"><div><h4>Where? Four offsets</h4><div class="ssd-offsets">${["move x","move y","resize w","resize h"].map((name,i)=>`<div><small>${name}</small>${fixed(offsets[i],1)}</div>`).join("")}</div><p class="ssd-small">Relative to the prior.<br>These are not pixel distances.</p></div>
      <div><h4>What? 21 class scores</h4>${scoreBars()}<p class="ssd-small">20 object classes + background.<br>Softmax converts logits into scores.</p></div></div>
      <p>Prediction heads are learned convolutions. They use feature values and shared weights to produce these numbers at every location. The inference pass does not train those weights.</p>
      <details><summary>Head dimensions and all example scores</summary><p>${k} priors per cell require <strong>${k}×4 = ${k*4}</strong> location channels and <strong>${k}×21 = ${k*21}</strong> class-logit channels. Across all maps: 7,668 offsets and 40,257 logits. Softmax operates over 21 classes separately for each prior.</p><table class="ssd-table"><thead><tr><th>Class</th><th>Example logit</th><th>Score</th></tr></thead><tbody>${M.LABELS.map((name,i)=>`<tr><td>${name}</td><td>${fixed(logits[i],1)}</td><td>${fixed(scores[i],4)}</td></tr>`).join("")}</tbody></table><p>Scores sum to one for this prior. A score is model confidence, not a guarantee of correctness.</p></details>`;
    if (stage === 3) return `<span class="ssd-tag toy">ILLUSTRATIVE BOX ARITHMETIC</span>
      <p>The dashed reference becomes the solid candidate. The first two offsets shift its center relative to its size; the other two expand or shrink its dimensions.</p>
      <table class="ssd-table"><thead><tr><th>Model-input pixels</th><th>Prior</th><th>Decoded</th></tr></thead><tbody>${["cx","cy","w","h"].map((key,i)=>`<tr><td>${["Center x","Center y","Width","Height"][i]}</td><td>${fixed(prior[key]*300,1)}</td><td>${fixed(decoded[key]*300,1)}</td></tr>`).join("")}</tbody></table>
      <p>The model’s <code>CENTER_SIZE</code> rule includes scale factors 0.1 for position and 0.2 for size. Zero offsets would leave the reference box unchanged.</p>
      <details><summary>Follow the exact calculation</summary><div class="ssd-equation">cx = prior.cx + 0.1 × tx × prior.w<br>cy = prior.cy + 0.1 × ty × prior.h<br>w = prior.w × exp(0.2 × tw)<br>h = prior.h × exp(0.2 × th)</div><p>For the x center: ${fixed(prior.cx*300,2)} + 0.1 × ${offsets[0]} × ${fixed(prior.w*300,2)} = ${fixed(decoded.cx*300,2)} pixels. Width multiplies by exp(0.2 × ${offsets[2]}) = ${fixed(Math.exp(.2*offsets[2]),3)}. Exponentiation keeps the decoded width and height positive.</p><p>Corners follow from center and size: left = cx − w/2, right = cx + w/2; similarly for top and bottom. Coordinates inside the model are normalized to image width/height.</p></details>`;
    if (stage === 4) {
      const boxes = candidates(decoded), decisions = M.suppress(boxes);
      const reasons = {A:"Keep", B:`NMS: IoU with A = ${fixed(M.iou(boxes[0].box,boxes[1].box))}`, C:"EdgeXR score < 0.5", D:"Graph score ≤ 0.25"};
      return `<span class="ssd-tag toy">ILLUSTRATIVE CANDIDATES</span><p>Several priors can predict the same object. Postprocessing reduces the duplicates before EdgeXR draws the boxes.</p>
        <table class="ssd-table"><thead><tr><th>Chair box</th><th>Score</th><th>Decision</th></tr></thead><tbody>${decisions.map(box=>`<tr><td>${box.id}</td><td>${fixed(box.score)}</td><td>${box.reason === "keep" ? "Keep" : box.id === "B" ? reasons.B : box.reason.startsWith("overlaps") ? "NMS: overlaps a higher-score box" : reasons[box.id]}</td></tr>`).join("")}</tbody></table>
        <p><strong>Inside the graph:</strong> exclude background and scores ≤ 0.25, then keep high-score boxes while suppressing same-class overlaps with IoU &gt; 0.45. This is non-maximum suppression (NMS).</p>
        <p><strong>Inside EdgeXR:</strong> <code>parse_detections()</code> keeps scores ≥ 0.5, clips corners to image bounds and discards empty boxes.</p>
        <details><summary>Why overlap does not always mean a duplicate</summary><p>NMS here is class-wise: an overlapping chair and person can both remain. IoU is intersection area divided by union area. The graph also applies top-k caps (100 per-class candidates before NMS and 100 final detections); our four-box example never reaches those limits.</p><p>NMS compares boxes within one inference result. The tracker’s later IoU matching compares boxes across detector updates to assign IDs. Those are different decisions.</p></details>`;
    }
    const chair = data.detections.find(box => box.label === "chair");
    return `<span class="ssd-tag">ACTUAL SAVED PI RESULT</span><p><code>net.forward()</code> returns rows shaped like:</p>
      <div class="ssd-equation">[image_id, class_id, score,<br> left, top, right, bottom]</div>
      <p>The box corners are normalized. EdgeXR multiplies x coordinates by <strong>1280</strong> and y coordinates by <strong>720</strong>, clips them, and rounds outward to pixel boundaries.</p>
      <div class="ssd-equation">Illustrative normalized box [0.1, 0.2, 0.3, 0.4]<br>→ source xyxy [128, 144, 384, 288]</div>
      <p>Your saved chair detection has confidence <strong>${fixed(chair.confidence,3)}</strong> and source box <code>[${chair.box_xyxy.join(", ")}]</code>. The dining-table box is also from that recorded report.</p>
      <p>Live detection later sends accepted boxes to <code>BasicTracker.update()</code> for IDs, then publishes the latest result for the browser. SSD itself does not give objects persistent IDs.</p>
      <p class="ssd-small">The saved report contains final boxes. It does not tell us which prior or intermediate activations produced each box.</p>`;
  }

  /** Render all dependent views from one stage/scale/shape state. @returns {void} */
  function render() {
    const state = current();
    draw(state); selectors(state);
    const boundary = stage === 4 ? "GRAPH + EDGEXR FILTER" : stage === 5 ? "EDGEXR PYTHON + SAVED REPORT" : "INSIDE NET.FORWARD()";
    $("ssd-stage-label").textContent = `${boundary} / ${stage+1} OF 6`;
    $("ssd-title").textContent = titles[stage];
    $("ssd-explain").innerHTML = explanation(state);
    $("ssd-back").disabled = stage === 0;
    $("ssd-next").textContent = stage === 5 ? "Restart SSD →" : "Next step →";
    $("ssd-progress").textContent = `Step ${stage+1}/6 · ${titles[stage]}`;
    document.querySelectorAll("[data-ssd-stage]").forEach(button => {
      if (Number(button.dataset.ssdStage) === stage) button.setAttribute("aria-current", "step");
      else button.removeAttribute("aria-current");
    });
  }

  // Controls are independent of the earlier convolution playback. Selection
  // survives Back/Next; keyboard users keep focus on the replacement button.
  document.querySelector(".ssd-stages").addEventListener("click", event => {
    const button = event.target.closest("[data-ssd-stage]");
    if (button) { stage = Number(button.dataset.ssdStage); render(); }
  });
  $("ssd-scales").addEventListener("click", event => {
    const button = event.target.closest("[data-ssd-head]");
    if (button) {
      headIndex = Number(button.dataset.ssdHead); priorIndex = 0; render();
      document.querySelector(`[data-ssd-head="${headIndex}"]`).focus({preventScroll:true});
    }
  });
  $("ssd-priors").addEventListener("click", event => {
    const button = event.target.closest("[data-ssd-prior]");
    if (button) {
      priorIndex = Number(button.dataset.ssdPrior); render();
      document.querySelector(`[data-ssd-prior="${priorIndex}"]`).focus({preventScroll:true});
    }
  });
  $("ssd-back").addEventListener("click", () => { stage = Math.max(0, stage-1); render(); });
  $("ssd-next").addEventListener("click", () => {
    stage = (stage+1)%6;
    if (stage === 0) { headIndex = 0; priorIndex = 0; }
    render();
  });
  render();
})();
